/**
 * Incident response toolkit generator
 * ------------------------------------
 * Generates an in-repo incident response policy scaffold plus the
 * surrounding artifacts: starter playbooks for the most common scenarios,
 * a tabletop exercise template, a severity classification reference,
 * and a security-incident issue template.
 *
 * Like the secure-coding generator, this does NOT produce AGENTS.md.
 * The AI usage policy baseline owns AGENTS.md; the IR toolkit produces
 * complementary artifacts that an AGENTS.md (if present) can reference.
 */

const POLICYFORGE_VERSION = '0.1.0';

function generateIncidentResponseFiles({ review, baseline, stack }) {
  const files = {};

  // 1. The in-repo policy scaffold (the centerpiece — same pattern as SC)
  files['docs/INCIDENT_RESPONSE_POLICY.md'] = renderPolicyScaffold({ review, baseline, stack });

  // 2. Severity classification reference card
  files['docs/severity-classification.md'] = renderSeverityReference({ stack });

  // 3. Tabletop exercise template
  files['docs/tabletop-exercise-template.md'] = renderTabletopTemplate({ stack });

  // 4. Starter playbooks (always produced — these are the reusable substance)
  files['docs/playbooks/data-breach.md']        = renderDataBreachPlaybook({ stack });
  files['docs/playbooks/ransomware.md']         = renderRansomwarePlaybook({ stack });
  files['docs/playbooks/phishing.md']           = renderPhishingPlaybook({ stack });
  files['docs/playbooks/ai-data-leak.md']       = renderAiDataLeakPlaybook({ stack });
  files['docs/playbooks/ai-prompt-injection.md'] = renderAiPromptInjectionPlaybook({ stack });

  // 5. GitHub issue template (only if GH-flavored CI)
  if (stack.ci === 'github-actions' || stack.ci === 'both' || !stack.ci) {
    files['.github/ISSUE_TEMPLATE/security-incident.md'] = renderIssueTemplate({ stack });
  }

  // 6. Toolkit README
  files['README.md'] = renderToolkitReadme({ review, stack });

  // 7. PolicyForge metadata
  files['.policyforge.json'] = JSON.stringify({
    generated_at: new Date().toISOString(),
    policyforge_version: POLICYFORGE_VERSION,
    baseline_id: baseline.baseline.id,
    baseline_version: baseline.baseline.version,
    stack
  }, null, 2);

  return files;
}

