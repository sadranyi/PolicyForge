function renderTabletopTemplate({ stack }) {
  return `# Tabletop Exercise Template

> Use this template to design and run a tabletop exercise validating your incident response policy. Save the completed exercise as \`docs/exercises/YYYY-QN-shortname.md\`.

## Exercise metadata

- **Date:** [YYYY-MM-DD]
- **Facilitator:** [name]
- **Participants:** [list — IR Coordinator, technical responders, Legal Lead, Communications Lead, Executive Sponsor as appropriate]
- **Duration:** [typically 90 minutes]
- **Scenario class:** [external attacker / insider / third-party / AI-related / regulatory]
- **Goal:** [what aspect of the IR plan is this exercise designed to validate?]

## Pre-exercise preparation

Facilitator prepares:

- Scenario narrative — initial trigger, time pressure, and a few revealed-as-you-go details
- A list of decision points the participants will face
- Reference materials (the IR policy, severity card, relevant playbooks) — but participants should not have these in front of them at the start; the test is whether they know the policy

## Scenario narrative

> [Write 2-3 paragraphs introducing the scenario. Include realistic detail: who reported it, what they saw, what time it is, what's known and what's unknown. Do not over-specify — leave gaps that participants will discover.]

> [Example for an AI data leak: "It is Tuesday at 3:47 PM. A senior data engineer just messaged the on-call engineer privately to admit that earlier today, while debugging a customer support ticket, they pasted the entire ticket text — including the customer's name, account ID, and a reference to their MRR figure — into ChatGPT to help draft a reply. They didn't think about it at the time, but a colleague's offhand comment in standup made them realize it might be a problem. They are willing to cooperate fully but are clearly anxious about consequences."]

## Decision points

The exercise is structured around five to seven decision points the participants must address. Reveal each one in sequence; do not show downstream decisions until the current one is resolved.

### Decision 1: Initial classification

- What is the initial severity?
- Who needs to know in the first 30 minutes?
- What is the on-call engineer's first action?

### Decision 2: [scope-discovery decision]

- [Reveal new information that changes the picture]
- What does the team need to find out next?
- Who is responsible for that finding?

### Decision 3: [communications decision]

- [Pose the question of internal/external/regulatory comms]
- What does the policy say?
- Who decides? Who drafts? Who approves?

### Decision 4: [containment/eradication decision]

### Decision 5: [recovery decision]

### Decision 6: [PIR-related decision]

## Observation prompts

While the exercise runs, the facilitator records:

- Where did participants reach for the policy / runbook? Did they find what they needed?
- Where did participants disagree? Did the policy resolve the disagreement?
- Where did the timeline drift? Were SLAs met?
- Where did people improvise? Was the improvisation reasonable, or did it indicate a missing playbook?

## After-action report

After the exercise, the facilitator writes a brief AAR covering:

- **Scenario summary** — one paragraph
- **What worked** — controls, processes, and team behaviors that performed well
- **What didn't work** — gaps in policy, runbooks, tooling, training, or team awareness
- **Corrective actions** — specific changes with named owners and due dates
- **Closure tracking** — corrective actions feed the same backlog as PIR actions

The AAR is reviewed at the next IRT meeting. Open corrective actions are tracked through closure.

## Suggested scenario rotations

For organizations running quarterly tabletops, rotate through these classes to cover different aspects of the IR plan:

- **Q1: External attacker** — credential theft, lateral movement, exfiltration. Tests detection, containment, regulatory analysis.
- **Q2: Insider** — departing employee or compromised admin. Tests evidence preservation, HR coordination, Legal involvement.
- **Q3: Third-party / supply chain** — vendor compromise affecting your environment. Tests external dependencies, communication with the vendor, scope assessment under uncertainty.
- **Q4: AI-related** — customer data into LLM, agent misbehavior, prompt injection. Tests the AI-specific playbooks and the readiness of teams that may not have trained on these classes.
`;
}

