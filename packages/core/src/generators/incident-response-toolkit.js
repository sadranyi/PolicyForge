function renderSeverityReference({ stack }) {
  return `# Severity Classification Reference

A quick-reference card for on-call responders. The full definitions live in the IR policy; this is the version you keep open during triage.

## Severity tiers

| Tier | Definition | Examples | Acknowledge | Contain |
|---|---|---|---|---|
| **S1 — Critical** | Active, ongoing harm; major customer impact; regulated data confirmed exposed | Customer DB compromised; production outage with security cause; mass credential compromise | 15 min | 1 hour |
| **S2 — High** | Confirmed incident with limited scope; possible regulated-data exposure | Single account compromise; secrets in AI service; agent misbehavior; isolated malware | 30 min | 4 hours |
| **S3 — Medium** | Confirmed incident, no regulated data, limited operational impact | Failed phishing some clicked; minor config exposure; suspected insider misuse without confirmed access | 4 hours | 1 business day |
| **S4 — Low** | Confirmed but minor; tracked for awareness | Successfully blocked attack; benign report | 1 business day | — |

## When to escalate severity

Initial severity is set on declaration and may be revised as scope becomes clear. **Always revise upward when:**

- Customer or regulated data is confirmed in scope
- Multiple systems or accounts are affected
- An attacker has persistence or lateral movement capability
- Public disclosure (social media, press) becomes likely
- Regulatory notification timer (GDPR 72h, NIS2 24h, SEC 4 business days) is potentially triggered

**Revising downward** requires IR Coordinator approval and a documented justification — usually because the initial assessment was overly conservative or the scope is now confirmed smaller than feared.

## Notification triggers per tier

See the IR policy § 5 for the full matrix. Quick reference:

- **S1**: on-call → IR Coordinator → Legal Lead → CISO → CEO (in that sequence, all within 1 hour)
- **S2**: on-call → IR Coordinator → Legal Lead (if customer/regulated data possible) → CISO
- **S3**: on-call → IR Coordinator → CISO next business day
- **S4**: on-call only

## What "ack within X minutes" means

The acknowledging responder takes ownership of the incident through the next handoff. Acknowledgment is not "I saw the alert" — it is "I am driving this incident now, and the next status update at the cadence in § 6 will come from me or my designated handoff."

If you cannot acknowledge within the SLA, escalate to your secondary on-call. Auto-escalation is configured in PagerDuty for S1/S2 if the primary doesn't acknowledge within the SLA.

---

*This card is regenerated when the IR policy is regenerated. Edit the IR policy directly rather than this card.*
`;
}

