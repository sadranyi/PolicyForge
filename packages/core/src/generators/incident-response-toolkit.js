function renderCategorySection(category, findings) {
  const sectionNum = {
    'Foundational': null,            // already covered by §§ 1-3 above
    'Severity model': 4,
    'Response phases': 5,
    'Communications': 6,
    'AI-specific incidents': 7,
    'Testing': 8,
    'Training': 9,
    'Post-incident review': 10
  }[category];

  if (sectionNum === null) {
    // Foundational rules are summarized above; render only as a brief audit
    return `---

## Foundational rules — verification

The opening sections of this policy address the foundational rules. Confirm:

${findings.map(f => `- ${statusEmoji(f)} ${f.title}`).join('\n')}`;
  }

  const intro = {
    'Severity model': 'A severity model turns abstract incident handling into operational triage. The on-call engineer who declares an incident must know where it lands.',
    'Response phases': 'We follow the NIST IR lifecycle. Phases are distinct steps with explicit transition criteria, not loose phases that blend into each other.',
    'Communications': 'Communications during an incident determine whether the response is professional or chaotic. The internal cadence, customer disclosure, and regulatory notification each have different stakeholders, different stakes, and different rules.',
    'AI-specific incidents': 'Modern AI systems introduce incident classes traditional IR programs are not configured to handle. The classes named here are recognized at this organization.',
    'Testing': 'An untested IR plan is a hypothesis. Tabletop exercises validate the plan before it is exercised under pressure.',
    'Training': 'Engineers and operations staff are usually the first to detect incidents. They need to know the basics from day one.',
    'Post-incident review': 'PIRs convert incidents into organizational learning — but only when the cadence is enforced and the culture is non-punitive.'
  }[category] || '';

  const items = findings.map(f => renderRuleSubsection(f)).join('\n\n');

  return `---

## ${sectionNum}. ${category}

${intro}

${items}`;
}

function renderRuleSubsection(finding) {
  const status = finding.status === 'satisfied' ? '✓ Addressed'
               : finding.status === 'partial'   ? '◐ Partially addressed'
                                                : '▲ TODO';
  const severityBadge = `[${finding.severity}]`;

  let body;
  if (finding.status === 'satisfied') {
    const evidence = finding.positive_matches?.[0]?.matched_text || '(matched)';
    body = `**Status: ${status}.** Your source policy addresses this requirement.

> Evidence located in your policy: *"${truncate(evidence, 140)}"*

Carry this section forward as-is from your source policy when finalizing this document.

<details>
<summary>Rule details</summary>

${finding.description.trim()}

*Cited frameworks: ${finding.citations.join(', ')}*

</details>`;
  } else if (finding.status === 'partial') {
    body = `**Status: ${status}.** Your source policy mentions this topic but the language suggests it is not a hard requirement.

**Suggested rewrite:**

> ${indent(finding.suggested_resolution.trim(), '> ')}

*Cited frameworks: ${finding.citations.join(', ')}*`;
  } else {
    body = `**Status: ${status}.** Your source policy did not address this requirement.

${finding.description.trim()}

**Suggested resolution:**

> ${indent(finding.suggested_resolution.trim(), '> ')}

*Cited frameworks: ${finding.citations.join(', ')}*`;
  }

  return `### ${severityBadge} ${finding.title}

${body}`;
}

function statusEmoji(f) {
  return f.status === 'satisfied' ? '✓' : f.status === 'partial' ? '◐' : '▲';
}

