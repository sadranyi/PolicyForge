function renderAiPromptInjectionPlaybook({ stack }) {
  return `# Playbook — AI Prompt Injection

> Triggered when an AI model (chatbot, agent, or automation) received malicious instructions embedded in untrusted content and acted on them. Default severity: **S2**, escalates based on what action was triggered.

## Recognize the class

Prompt injection is the AI-era analog of SQL injection — data containing instructions that the model treats as commands. Two flavors:

- **Direct** — user types injection into the prompt (typically: jailbreak attempt against a customer-facing chatbot)
- **Indirect** — model fetches content (a document, web page, file, API response) that contains an injection. The user did not author the malicious instruction, but the model executed it.

Indirect prompt injection is the more dangerous class because it scales — an attacker who poisons a public web page can affect every model that reads that page.

## Initial response

1. **Declare** S2 by default. Escalate based on action triggered.
2. **Acknowledge** within 30 min.
3. **Preserve the inbound content** that contained the injection — the document, the email, the web page snapshot, the API response. This is the evidence.

## Determine impact

The severity scales with what the injected prompt caused the model to do:

| Action triggered | Likely severity |
|---|---|
| Model produced incorrect or attacker-directed output (no real-world action) | S3 |
| Model exfiltrated context to attacker (e.g., previous conversation, system prompt) | S2 |
| Model called a tool, sent an email, modified a file, or affected production data | S1 |
| Model accessed customer data and exposed it in output | S1 |

For agentic systems specifically, audit the action log, not just the conversation log. The conversation may show benign-looking text while the action log shows actual API calls, tool invocations, or file modifications.

## Determine attack vector

- **Direct**: user pasted the injection. Attacker is a customer or external person interacting with your chatbot.
- **Indirect via document**: model read a document containing instructions. Source: customer upload? Internal document? Email forwarded?
- **Indirect via web fetch**: model fetched a URL that contained instructions. Source: public web page? Customer-supplied URL? RSS feed?
- **Indirect via API**: model received a response from a third-party API that contained instructions. Source: which API? Was the API response unexpected?
- **Indirect via MCP server**: tool response contained instructions. Source: which MCP server? Compromised? Misconfigured?

## Containment

- If a specific source is identified (a poisoned document, a compromised MCP server), block or sanitize that source
- If the injection succeeded against a customer-facing model, take the model offline if continued exposure is meaningful (vs. logging and patching)
- For agentic systems: revoke any credentials the agent had access to and audit recent actions

## Eradication

- Update content-handling rules to detect and refuse the specific injection pattern
- Tighten prompts that the model receives — separate user instructions from fetched content with explicit boundaries
- For agentic systems, narrow the agent's permissions to least-privilege for its actual task

## Recovery

- Re-enable affected model after containment confirmed
- Monitor for similar attempts — successful injection typically gets reused
- Update detection patterns in your AI-content guard / SIEM

## Communications

- Internal: technical detail to engineering, impact summary to executive
- Customer: if customer data was exposed, Legal-led notification per breach process
- Public: typically not required for prompt injection alone unless it caused a breach

## PIR — special focus

Prompt injection PIRs surface gaps in how content is handled:

- Untrusted content was rendered into the model's context without isolation
- The model's tools had broader scope than the model's task required
- Detection patterns missed the injection because they assumed direct attack rather than indirect

Reference: [OWASP LLM Top 10 — LLM01: Prompt Injection](https://owasp.org/www-project-top-10-for-large-language-model-applications/) for the canonical taxonomy.

---

*Customize with your organization's actual model deployments, content sources, and escalation paths.*
`;
}

