/**
 * Toolkit generator
 * -----------------
 * Produces a tailored toolkit (set of files) based on:
 *   - The review findings (so generated AGENTS.md addresses gaps the policy missed)
 *   - The baseline (so we cite frameworks consistently)
 *   - The user's stack profile (language, CI, secrets store)
 *
 * Output is an object: { '/path/to/file': '<contents>' } — the caller
 * decides whether to write to disk or zip.
 */

const path = require('path');
const fs = require('fs');
const { generateSecureCodingFiles } = require('./secure-coding-toolkit');
const { generateIncidentResponseFiles } = require('./incident-response-toolkit');

function generateToolkit({ review, baseline, stack }) {
  // Dispatch by baseline ID. Each baseline owns a distinct enforcement surface,
  // so each gets its own generator. Adding a new baseline means adding a case
  // here and a sibling generator file; the AI generator below stays unchanged.
  const baselineId = baseline?.baseline?.id;

  if (baselineId === 'secure-coding-standards') {
    return generateSecureCodingFiles({ review, baseline, stack });
  }

  if (baselineId === 'incident-response') {
    return generateIncidentResponseFiles({ review, baseline, stack });
  }

  if (baselineId === 'ai-usage-policy' || !baselineId) {
    return generateAiUsageFiles({ review, baseline, stack });
  }

  // Unknown baseline ID — fail loudly rather than silently produce
  // AI-flavored output (which is what would happen if we fell through).
  const err = new Error(
    `No toolkit generator available for baseline "${baselineId}". ` +
    `Supported: ai-usage-policy, secure-coding-standards, incident-response.`
  );
  err.code = 'TOOLKIT_BASELINE_UNSUPPORTED';
  throw err;
}

// ============================================================
// AI usage policy toolkit — original generator, renamed
// ============================================================
function generateAiUsageFiles({ review, baseline, stack }) {
  const files = {};

  // 1. AGENTS.md — the canonical agent instructions
  files['AGENTS.md'] = renderAgentsMd({ review, baseline, stack });

  // 2. CLAUDE.md — redirector
  files['CLAUDE.md'] = renderClaudeRedirector();

  // 3. .github/copilot-instructions.md — redirector
  files['.github/copilot-instructions.md'] = renderCopilotRedirector(stack);

  // 4. The content guard script (Node, no deps)
  files['scripts/ai-content-guard.js'] = renderContentGuard({ stack });

  // 5. Pre-commit hooks — depends on stack
  if (stack.languages.includes('typescript') || stack.languages.includes('javascript') || stack.languages.includes('mixed')) {
    files['.husky/pre-commit'] = renderHuskyPreCommit();
    files['.husky/commit-msg'] = renderHuskyCommitMsg();
  }
  if (stack.languages.includes('csharp') || stack.languages.includes('mixed')) {
    files['.husky/task-runner.json'] = renderHuskyNetTaskRunner();
  }

  // 6. Gitleaks config
  files['.gitleaks.toml'] = renderGitleaksConfig();

  // 7. CI pipeline gates — depends on CI choice
  if (stack.ci === 'azure-devops' || stack.ci === 'both') {
    files['azure-pipelines/ai-policy-gates.yml'] = renderAzureDevOpsTemplate();
  }
  if (stack.ci === 'github-actions' || stack.ci === 'both') {
    files['.github/workflows/ai-policy-gates.yml'] = renderGitHubActionsWorkflow();
  }

  // 8. AI Incident Response runbook (markdown only — Word version is generated separately)
  files['docs/AI_Incident_Response_Runbook.md'] = renderRunbook({ baseline });

  // 9. README explaining the toolkit
  files['README.md'] = renderToolkitReadme({ review, stack });

  // 10. PolicyForge metadata (so users know which version generated this)
  files['.policyforge.json'] = JSON.stringify({
    generated_at: new Date().toISOString(),
    policyforge_version: '0.1.0',
    baseline_id: baseline.baseline.id,
    baseline_version: baseline.baseline.version,
    stack
  }, null, 2);

  return files;
}

