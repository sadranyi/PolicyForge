function renderPrTemplate({ review, stack }) {
  return `## Summary

<!-- What does this change do, and why? Link to the issue or design doc if applicable. -->

## Type of change

- [ ] Bug fix
- [ ] New feature
- [ ] Refactor (no behavior change)
- [ ] Documentation
- [ ] Build / CI / tooling
- [ ] Security fix *(if yes, please tag @app-security in the review)*

## Security review checklist

The following questions help reviewers spot security-sensitive changes early. Answer honestly — "no" answers are fine and common; this is an aid, not a gate.

### Data handling

- [ ] This change does **not** introduce new input from an external trust boundary (HTTP request, message queue, file upload, third-party service)
- [ ] If it does, every new input is validated with an allowlist before use
- [ ] This change does **not** log secrets, credentials, tokens, full request payloads of sensitive endpoints, or unredacted PII

### Authentication & authorization

- [ ] This change does **not** modify authentication, session management, or authorization logic
- [ ] If it does, the change has a server-side authorization check on every state-changing operation
- [ ] If it touches user-data access, the change includes an object-level authorization check (not just endpoint-level)

### Cryptography & secrets

- [ ] This change does **not** introduce a new cryptographic operation
- [ ] If it does, the algorithm is on the approved list (see \`docs/SECURE_CODING_STANDARDS.md\` § Cryptography)
- [ ] No secrets, API keys, tokens, or credentials are committed in this change *(secret scanning will catch this anyway)*

### Dependencies

- [ ] This change does **not** add a new third-party dependency
- [ ] If it does, the dependency comes from an approved source and has been on a recent release within 12 months
- [ ] No dependency was pinned to bypass a known vulnerability

### CI gates

- [ ] SAST passed (no new Critical or High findings introduced by this change)
- [ ] SCA passed (no new Critical CVE introduced)
- [ ] Secret scanning passed
- [ ] Tests pass

## Threat model

- [ ] This change does **not** modify a trust boundary
- [ ] If it does, the threat model has been updated *(see \`docs/security/threat-model.md\` if applicable)*

## Reviewer assignment

- [ ] Standard review — one approval required
- [ ] **Two reviewers required** — this change touches authentication, authorization, cryptography, key management, or external integrations *(see secure coding standard § Process for the full list)*

---

<!--
This template was generated by PolicyForge based on your secure coding standards review.
To customize: edit .github/PULL_REQUEST_TEMPLATE.md.
-->
`;
}

