// 1. The in-repo standard scaffold
// ============================================================
function renderStandardScaffold({ review, baseline, stack }) {
  const orgName = stack.org_name || 'Your Organization';
  const today = new Date().toISOString().slice(0, 10);
  const langDisplay = {
    typescript: 'TypeScript', javascript: 'JavaScript', csharp: 'C#',
    python: 'Python', java: 'Java', mixed: 'mixed languages'
  };
  const prettyLangs = (stack.languages || []).map(l => langDisplay[l] || l);
  const langList = prettyLangs.length ? prettyLangs.join(', ') : 'all production code';

  // Group findings by category, preserving the baseline's category order.
  const findingsByCategory = {};
  for (const f of review.findings) {
    const cat = f.category || 'General';
    if (!findingsByCategory[cat]) findingsByCategory[cat] = [];
    findingsByCategory[cat].push(f);
  }
  const orderedCategories = [
    'Foundational',
    'Input handling',
    'Authentication',
    'Authorization',
    'Cryptography',
    'Dependencies',
    'Logging',
    'Process',
    'Training'
  ].filter(c => findingsByCategory[c]);

  // Build category sections
  const sections = orderedCategories.map(cat => renderCategorySection(cat, findingsByCategory[cat])).join('\n\n');

  return `# ${orgName} — Secure Coding Standard

> **Status:** Generated by PolicyForge v${POLICYFORGE_VERSION} on ${today}
> **Source:** Reviewed against ${baseline.baseline.name} v${baseline.baseline.version}
> **Owner:** Application Security
> **Audience:** Engineers writing or reviewing production code in this repository

This document is the canonical secure-coding standard for ${orgName} repositories. It is organized by topic so that engineers can find the rules they need at the moment of decision — at code-review time, when designing a new service, when adding a dependency.

The text below was scaffolded from your existing policy review. **Items marked \`✓ Addressed\` were satisfied by your source policy and pulled forward; items marked \`▲ TODO\` are gaps that PolicyForge identified and you should resolve before adopting this standard.**

---

## 1. Scope

This standard applies to ${langList === 'all production code' ? langList : `all production code written in ${langList}`}, and to any service deployed outside the corporate network.

> **Out of scope** *(adjust as needed)*: research notebooks, internal tooling not exposed beyond the engineering VPN, and third-party SaaS configurations.

## 2. References

This standard depends on:

- **Data Classification Policy** — define or link your organization's data-classification taxonomy. Control intensity in this standard scales with classification tier.
- **Incident Response Policy** — security findings (in-prod Critical CVE, leaked secret, customer-reported issue) invoke this process.

${sections}

---

## Appendix: Compliance with this standard

Every change to a production-bound branch must pass:

1. **Code review** by at least one reviewer (two for security-sensitive paths — see Process section).
2. **CI gates** — SAST, SCA, secret scanning, and SBOM generation. See \`.github/workflows/security-gates.yml\` (or \`azure-pipelines/security-gates.yml\`).
3. **Pre-commit hooks** — secret scanning runs locally before every commit. See \`.husky/pre-commit\`.

Exceptions to these gates require Application Security approval, are recorded in writing, and are reviewed quarterly.

---

*This standard is reviewed at least annually by the Application Security team and revised whenever a Critical post-incident review reveals a relevant gap.*

*Last reviewed: ${today}*
`;
}

function renderCategorySection(category, findings) {
  const sectionNum = {
    'Foundational': 3,
    'Input handling': 4,
    'Authentication': 5,
    'Authorization': 6,
    'Cryptography': 7,
    'Dependencies': 8,
    'Logging': 9,
    'Process': 10,
    'Training': 11
  }[category] || '?';

  const intro = {
    'Foundational': 'These are the prerequisites — the things every other section assumes. If any of these are missing, the rest of the standard rests on sand.',
    'Input handling': 'Input validation and output encoding are the foundational defenses against injection, deserialization, and parser-confusion attacks.',
    'Authentication': 'Authentication failures are tracked separately from authorization failures because they have different remediation paths and different threat models.',
    'Authorization': 'Broken Access Control is OWASP Top 10 #1 for a reason — it\'s the failure mode that\'s easiest to introduce and hardest to detect.',
    'Cryptography': 'Cryptography rules are short and sharp on purpose. The goal is to take the decision out of the hands of the person writing the code.',
    'Dependencies': 'Most of the code in production is dependencies. A standard that addresses only first-party code ignores the larger attack surface.',
    'Logging': 'Logs are how incidents get reconstructed. They are also a top-three location for leaked secrets if not managed carefully.',
    'Process': 'No technical control replaces a competent second set of eyes. The process section ensures those eyes are looking at the right things.',
    'Training': 'A standard nobody has been trained on is shelfware.'
  }[category] || '';

  // Render findings — each becomes a subsection of this category
  const items = findings.map(f => renderRuleSubsection(f)).join('\n\n');

  return `---

## ${sectionNum}. ${category}

${intro}

${items}`;
}

function renderRuleSubsection(finding) {
  const status = finding.status === 'satisfied' ? '✓ Addressed'
               : finding.status === 'partial'   ? '◐ Partially addressed'
                                                : '▲ TODO';

  const severityBadge = `[${finding.severity}]`;

  // Body depends on status
  let body;
  if (finding.status === 'satisfied') {
    const evidence = finding.positive_matches?.[0]?.matched_text || '(matched)';
    body = `**Status: ${status}.** Your source policy addresses this requirement.

> Evidence located in your policy: *"${truncate(evidence, 140)}"*

Carry this section forward as-is from your source policy when finalizing this document. The full text of the rule and its citation are below for reference.

<details>
<summary>Rule details</summary>

${finding.description.trim()}

*Cited frameworks: ${finding.citations.join(', ')}*

</details>`;
  } else if (finding.status === 'partial') {
    body = `**Status: ${status}.** Your source policy mentions this topic but the language suggests it is not a hard requirement, or the wording matches a known weak phrasing.

**Suggested rewrite:**

> ${indent(finding.suggested_resolution.trim(), '> ')}

*Cited frameworks: ${finding.citations.join(', ')}*`;
  } else {
    // gap
    body = `**Status: ${status}.** Your source policy did not address this requirement.

${finding.description.trim()}

**Suggested resolution:**

> ${indent(finding.suggested_resolution.trim(), '> ')}

*Cited frameworks: ${finding.citations.join(', ')}*`;
  }

  return `### ${severityBadge} ${finding.title}

${body}`;
}

