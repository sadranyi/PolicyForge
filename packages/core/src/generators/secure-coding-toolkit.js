function truncate(s, n) {
  if (!s) return '';
  return s.length <= n ? s : s.slice(0, n) + '…';
}

function indent(s, prefix) {
  return s.split('\n').map((line, i) => i === 0 ? line : prefix + line).join('\n');
}

