// ============================================================
function renderHuskyPreCommit() {
  return `#!/usr/bin/env sh
# Pre-commit hook — secret scanning
#
# Runs gitleaks against staged changes. If a secret is detected,
# the commit is blocked until the secret is rotated and removed.
#
# To install: \`npm install --save-dev husky && npx husky install\`

. "$(dirname -- "$0")/_/husky.sh"

# Check for gitleaks
if ! command -v gitleaks > /dev/null 2>&1; then
  echo "⚠ gitleaks is not installed. Install from https://github.com/gitleaks/gitleaks"
  echo "  Skipping secret scan — your commit will be checked again in CI."
  exit 0
fi

# Run gitleaks against staged changes only
echo "🔍 Scanning staged changes for secrets..."
if ! gitleaks protect --staged --redact --config .gitleaks.toml; then
  echo ""
  echo "✗ Secret scan failed."
  echo "  If a real secret was detected:"
  echo "    1. Rotate the secret immediately."
  echo "    2. Unstage the file ($ git restore --staged <file>) and remove the secret."
  echo "    3. If the secret was already committed, follow the secret-purge runbook."
  echo "  If this is a false positive:"
  echo "    Add an inline allowlist comment per gitleaks docs, or update .gitleaks.toml."
  exit 1
fi
echo "✓ No secrets detected in staged changes."
`;
}

