// 5. CI gates — GitHub Actions
// ============================================================
function renderGitHubSecurityGates({ stack }) {
  const langs = stack.languages || [];
  const codeqlLanguages = [];
  if (langs.includes('typescript') || langs.includes('javascript') || langs.includes('mixed')) codeqlLanguages.push('javascript-typescript');
  if (langs.includes('csharp') || langs.includes('mixed')) codeqlLanguages.push('csharp');
  if (langs.includes('python') || langs.includes('mixed')) codeqlLanguages.push('python');
  if (langs.includes('java') || langs.includes('mixed')) codeqlLanguages.push('java-kotlin');
  const codeqlMatrix = codeqlLanguages.length > 0 ? codeqlLanguages : ['javascript-typescript'];

  return `# .github/workflows/security-gates.yml
#
# Security gates that run on every PR and on push to main.
# Generated by PolicyForge from your secure coding standards review.
#
# Gates implemented:
#   1. SAST   — CodeQL static analysis
#   2. SCA    — dependency vulnerability scanning (Dependabot is configured separately)
#   3. Secrets — gitleaks
#   4. SBOM   — software bill of materials (Syft)
#
# Build fails on Critical findings. Suppressions go in the relevant tool's config.

name: Security gates

on:
  pull_request:
    branches: [main]
  push:
    branches: [main]

permissions:
  contents: read
  security-events: write
  pull-requests: read

jobs:
  sast-codeql:
    name: SAST (CodeQL)
    runs-on: ubuntu-latest
    strategy:
      fail-fast: false
      matrix:
        language: [${codeqlMatrix.map(l => `'${l}'`).join(', ')}]
    steps:
      - uses: actions/checkout@v4

      - name: Initialize CodeQL
        uses: github/codeql-action/init@v3
        with:
          languages: \${{ matrix.language }}
          # security-and-quality is the recommended query suite — broader than 'security-extended'
          # which only includes high-precision queries. Adjust if you need a tighter signal.
          queries: security-and-quality

      - name: Autobuild
        uses: github/codeql-action/autobuild@v3

      - name: Perform CodeQL analysis
        uses: github/codeql-action/analyze@v3
        with:
          category: '/language:\${{ matrix.language }}'

  secret-scan:
    name: Secret scan (gitleaks)
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0

      - name: Run gitleaks
        uses: gitleaks/gitleaks-action@v2
        env:
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          GITLEAKS_CONFIG: .gitleaks.toml

  sbom:
    name: Generate SBOM (Syft)
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Generate SBOM
        uses: anchore/sbom-action@v0
        with:
          format: cyclonedx-json
          output-file: sbom.cyclonedx.json

      - name: Upload SBOM artifact
        uses: actions/upload-artifact@v4
        with:
          name: sbom
          path: sbom.cyclonedx.json
          retention-days: 90

  # ---------------------------------------------------------------------
  # Tip: Dependency scanning runs continuously via Dependabot — see
  # .github/dependabot.yml. To enforce remediation SLAs, configure required
  # status checks on Dependabot PRs in repo settings.
  # ---------------------------------------------------------------------
`;
}

function renderDependabotConfig({ stack }) {
  const langs = stack.languages || [];
  const ecosystems = [];
  if (langs.includes('typescript') || langs.includes('javascript') || langs.includes('mixed')) {
    ecosystems.push({
      'package-ecosystem': 'npm',
      directory: '/'
    });
  }
  if (langs.includes('csharp') || langs.includes('mixed')) {
    ecosystems.push({
      'package-ecosystem': 'nuget',
      directory: '/'
    });
  }
  if (langs.includes('python') || langs.includes('mixed')) {
    ecosystems.push({
      'package-ecosystem': 'pip',
      directory: '/'
    });
  }
  if (langs.includes('java') || langs.includes('mixed')) {
    ecosystems.push({
      'package-ecosystem': 'maven',
      directory: '/'
    });
  }
  if (ecosystems.length === 0) {
    ecosystems.push({ 'package-ecosystem': 'npm', directory: '/' });
  }
  // Always also scan the GitHub Actions workflows themselves
  ecosystems.push({ 'package-ecosystem': 'github-actions', directory: '/' });

  const updates = ecosystems.map(e => `  - package-ecosystem: "${e['package-ecosystem']}"
    directory: "${e.directory}"
    schedule:
      interval: "weekly"
    open-pull-requests-limit: 10
    labels:
      - "dependencies"
      - "security"`).join('\n\n');

  return `# .github/dependabot.yml
#
# Dependabot configuration generated by PolicyForge.
# Continuous dependency scanning is required by your secure coding standard.
# Adjust the schedule, ecosystems, and labels as your team's intake capacity allows.

version: 2
updates:
${updates}
`;
}

