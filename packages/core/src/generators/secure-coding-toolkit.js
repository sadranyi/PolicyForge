/**
 * Secure-coding-standards toolkit generator
 * -----------------------------------------
 * Generates an in-repo secure coding standard scaffold plus the surrounding
 * enforcement artifacts (PR template, threat-model template, SAST/SCA gates,
 * AI-agent secure-coding rules).
 *
 * Intentionally does NOT produce AGENTS.md. The AI usage policy baseline
 * owns AGENTS.md; the secure-coding baseline produces a complementary
 * docs/SECURE_CODING_FOR_AI_AGENTS.md that an AGENTS.md (if one exists)
 * can reference.
 *
 * Output shape: { 'path/to/file': '<contents>' } — same convention as
 * the AI toolkit generator, so the caller (CLI / web) needs no changes.
 */

const fs = require('fs');
const path = require('path');

const POLICYFORGE_VERSION = '0.1.0';

// ============================================================
// Public entry point
// ============================================================
function generateSecureCodingFiles({ review, baseline, stack }) {
  const files = {};

  // 1. The in-repo standard scaffold (the most important artifact)
  files['docs/SECURE_CODING_STANDARDS.md'] = renderStandardScaffold({ review, baseline, stack });

  // 2. AI-agent rules — separate file, referenced from AGENTS.md if present
  files['docs/SECURE_CODING_FOR_AI_AGENTS.md'] = renderAiAgentRules({ review, baseline, stack });

  // 3. Threat model template
  files['docs/THREAT_MODEL_TEMPLATE.md'] = renderThreatModelTemplate({ stack });

  // 4. PR template — drops directly into developer flow
  files['.github/PULL_REQUEST_TEMPLATE.md'] = renderPrTemplate({ review, stack });

  // 5. CI gates — depends on chosen CI
  if (stack.ci === 'github-actions' || stack.ci === 'both') {
    files['.github/workflows/security-gates.yml'] = renderGitHubSecurityGates({ stack });
    files['.github/dependabot.yml'] = renderDependabotConfig({ stack });
  }
  if (stack.ci === 'azure-devops' || stack.ci === 'both') {
    files['azure-pipelines/security-gates.yml'] = renderAzureSecurityGates({ stack });
  }

  // 6. Pre-commit hooks — secret scanning is the canonical pre-commit check
  if (stack.languages.includes('typescript') || stack.languages.includes('javascript') || stack.languages.includes('mixed')) {
    files['.husky/pre-commit'] = renderHuskyPreCommit();
  }
  if (stack.languages.includes('csharp') || stack.languages.includes('mixed')) {
    files['.husky/task-runner.json'] = renderHuskyNetTaskRunner();
  }

  // 7. Gitleaks configuration
  files['.gitleaks.toml'] = renderGitleaksConfig();

  // 8. Toolkit README — explains how to install
  files['README.md'] = renderToolkitReadme({ review, stack });

  // 9. PolicyForge metadata
  files['.policyforge.json'] = JSON.stringify({
    generated_at: new Date().toISOString(),
    policyforge_version: POLICYFORGE_VERSION,
    baseline_id: baseline.baseline.id,
    baseline_version: baseline.baseline.version,
    stack
  }, null, 2);

  return files;
}

